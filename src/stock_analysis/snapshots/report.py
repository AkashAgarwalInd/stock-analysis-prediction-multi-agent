"""Human-readable report rendered from a validated ``ForecastSnapshot``.

The writer is deterministic: it only formats values already in the snapshot.
It never computes new figures (no deltas, counts or derived percentages beyond
displaying a probability as a percentage), and ``render_forecast_report``
refuses to return a report containing a number it cannot trace back to the
snapshot.
"""

from __future__ import annotations

import re
from typing import Any, Iterable, Optional

from stock_analysis.schemas.forecast_pipeline import ForecastAdjustmentType
from stock_analysis.schemas.memory import LastReview, MemoryContext, PreRunReview
from stock_analysis.schemas.snapshot import ForecastSnapshot

DISCLAIMER = (
    "This output is generated by an automated system for educational and demonstration "
    "purposes only. It is not investment advice, and forecasts are probabilistic estimates "
    "that may be wrong. Do not make financial decisions based on this output."
)

# A number not glued to a preceding word character (so "P10" or "v2" are labels).
_NUMBER_RE = re.compile(r"(?<![\w.])\d+(?:\.\d+)?")
# Explicit recommendation phrasing in LLM-written text. Deliberately narrow:
# market vocabulary such as "sell-off" or "support holds" must not trip it.
_ADVICE_RE = re.compile(
    r"\b(?:strong|outright)\s+(?:buy|sell)\b"
    r"|\b(?:buy|sell|hold)\s+(?:signal|rating|call|recommendation)s?\b"
    r"|\brecommend(?:s|ed|ing)?\s+(?:buying|selling|holding)\b"
    r"|\b(?:target\s+price|price\s+target)\b"
    r"|\baccumulate\b",
    re.IGNORECASE,
)
ADVICE_WORDING_NOTE = (
    "Some analyst or predictor text uses recommendation-style wording; it is quoted "
    "as generated and is not advice."
)
_MIN_STRIP_LEN = 3

_PROB_ADJUSTMENTS = {
    ForecastAdjustmentType.PROB_UP,
    ForecastAdjustmentType.PROB_FLAT,
    ForecastAdjustmentType.PROB_DOWN,
}
_PRICE_ADJUSTMENTS = {
    ForecastAdjustmentType.P10_PRICE,
    ForecastAdjustmentType.P50_PRICE,
    ForecastAdjustmentType.P90_PRICE,
}


class ReportIntegrityError(ValueError):
    """The rendered report contains numbers that are not in the snapshot."""


def _price(v: float) -> str:
    return f"₹{v:.2f}"


def _prob(v: float) -> str:
    return f"{v * 100:.1f}%"


def _ret(v: float) -> str:
    return f"{v:+.2f}%"


def _yes_no(flag: bool) -> str:
    return "yes" if flag else "no"


def _adjustment_value(kind: ForecastAdjustmentType, v: float) -> str:
    if kind in _PROB_ADJUSTMENTS:
        return _prob(v)
    if kind in _PRICE_ADJUSTMENTS:
        return _price(v)
    return f"{v:.2f}%"


def _bullets(items: Iterable[str], empty: str) -> list[str]:
    lines = [f"- {item}" for item in items]
    return lines or [f"- {empty}"]


def _distribution_rows(label_values: list[tuple[str, str, str]]) -> list[str]:
    return [
        "| Metric | Quant baseline | Final forecast |",
        "|---|---|---|",
        *(f"| {label} | {base} | {final} |" for label, base, final in label_values),
    ]


def _llm_text(snapshot: ForecastSnapshot) -> list[str]:
    """Every free-text field in the snapshot that an LLM wrote."""
    final = snapshot.final_forecast
    texts = [final.predictor_reasoning, *final.evidence, *final.risks]
    texts += [adj.reason for adj in final.adjustments]
    for report in snapshot.analyst_reports.values():
        for key in ("key_points", "evidence", "risks"):
            texts += [str(item) for item in (report or {}).get(key, [])]
    return texts


def has_advice_wording(snapshot: ForecastSnapshot) -> bool:
    """True if LLM-written text in ``snapshot`` contains recommendation-style phrasing."""
    return any(_ADVICE_RE.search(text) for text in _llm_text(snapshot))


def _prior_context_lines(memory: Optional[dict[str, Any]]) -> list[str]:
    """Earlier forecasts, active lessons and track record the run was given."""
    if memory is None:
        return ["- Memory was not configured for this run."]
    context = MemoryContext.model_validate(memory)
    if not context.loaded:
        return [f"- Memory could not be loaded: {context.error}"]

    lines = [
        f"- Previous forecast `{f.forecast_id}` (as of {f.as_of_date.isoformat()}, target "
        f"{f.target_date.isoformat()}): regime {f.market_regime}; P(up) {_prob(f.prob_up)}; "
        f"P50 {_price(f.p50_price)}; adjustment applied: {_yes_no(f.adjustment_applied)}"
        for f in context.prior_forecasts
    ]
    lines += [
        f"- Active lesson ({lesson.scope}, {lesson.evidence_count} confirmations): {lesson.text}"
        for lesson in context.active_lessons
    ]
    if not lines:
        lines.append("- No earlier forecasts or active lessons for this ticker.")
    track = context.track_record
    if track is not None:
        lines.append(
            f"- Track record: earlier forecasts {track.forecasts_made}; scored against actual "
            f"prices {track.forecasts_scored}; awaiting evaluation "
            f"{track.forecasts_awaiting_outcome}."
        )
    lines += [f"- Warning: {w}" for w in context.warnings]
    return lines


def _review_run_lines(review: Optional[dict[str, Any]]) -> list[str]:
    """What the review run just before this forecast did."""
    if review is None:
        return []
    r = PreRunReview.model_validate(review)
    line = (
        f"- Review before this run: {r.matured} matured forecasts; {r.scored} scored, "
        f"{r.invalid} invalid, {r.unresolved} awaiting data; {r.postmortems} postmortems; "
        f"lessons created {r.lessons_created}, updated {r.lessons_updated}"
    )
    if r.calibration_version is not None:
        line += f"; calibration v{r.calibration_version} stored"
    return [line, *(f"- Review error: {e}" for e in r.errors)]


def _learning_memory(snapshot: ForecastSnapshot) -> Optional[MemoryContext]:
    """The run's memory if learning context was loaded into it (Plan.md Phase 16)."""
    memory = snapshot.data_inputs.get("memory")
    if memory is None:
        return None
    context = MemoryContext.model_validate(memory)
    return context if context.loaded and context.learning_loaded else None


def _value_added(value: Optional[float], what: str) -> str:
    if value is None:
        return "n/a"
    if value > 0:
        return f"{value:+.4f} (lower loss than the {what})"
    if value < 0:
        return f"{value:+.4f} (higher loss than the {what})"
    return f"{value:.4f} (same loss as the {what})"


_NOT_LOADED = "- Not available for this run (not configured, or see the warnings under Prior context)."


def _band(low: Optional[float], high: Optional[float], inside: Optional[bool]) -> str:
    if low is None or high is None:
        return "n/a"
    where = "" if inside is None else (" (inside)" if inside else " (OUTSIDE)")
    return f"{_price(low)}–{_price(high)}{where}"


def _call(direction: Optional[str], prob_up: Optional[float], correct: Optional[bool]) -> str:
    if direction is None:
        return "n/a"
    text = direction.upper()
    if prob_up is not None:
        text += f" (P(up) {_prob(prob_up)})"
    if correct is not None:
        text += " — correct" if correct else " — wrong"
    return text


def _last_review_lines(context: MemoryContext) -> list[str]:
    """Plan.md §29/§57 "Last forecast vs actual" with the baseline-vs-final attribution
    (Plan.md §56 part 4), copied from the stored outcome."""
    if "last_review" not in context.learning_loaded:
        return [_NOT_LOADED]
    review: Optional[LastReview] = context.last_review
    if review is None:
        return ["- No earlier forecast of this ticker has been evaluated yet."]
    lines = [
        f"- Forecast `{review.forecast_id}` (as of {review.as_of_date.isoformat()}, target "
        f"{review.target_date.isoformat()})"
    ]
    if review.status != "scored" or review.actual_close is None:
        return [*lines, f"- Not evaluated: {review.invalid_reason}"]

    def error(v: Optional[float]) -> str:
        return "n/a" if v is None else _ret(v)

    def loss(v: Optional[float]) -> str:
        return "n/a" if v is None else f"{v:.4f}"

    base_p50 = "n/a" if review.baseline_p50_price is None else _price(review.baseline_p50_price)
    base_band = _band(
        review.baseline_p10_price, review.baseline_p90_price, review.baseline_in_80pct_band
    )
    base_call = _call(
        review.baseline_direction, review.baseline_prob_up, review.baseline_direction_correct
    )
    final_call = _call(review.predicted_direction, review.prob_up, review.direction_correct)
    lines += [
        "",
        "| | Quant baseline | Final forecast | Actual |",
        "|---|---|---|---|",
        f"| P50 / close | {base_p50} | {_price(review.p50_price)} "
        f"| {_price(review.actual_close)} |",
        f"| P10–P90 range | {base_band} "
        f"| {_band(review.p10_price, review.p90_price, review.in_80pct_band)} | |",
        f"| Direction | {base_call} | {final_call} | {str(review.realized_direction).upper()} |",
        f"| Error vs P50 | {error(review.baseline_signed_error_pct)} "
        f"| {error(review.signed_error_pct)} | |",
        f"| Up/flat/down Brier | {loss(review.baseline_loss)} | {loss(review.final_loss)} | |",
        "",
    ]
    if review.actual_return_pct is not None:
        lines.append(f"- Actual return: {_ret(review.actual_return_pct)}")
    if review.nifty_return_pct is not None:
        excess = review.excess_vs_nifty_pct
        lines.append(
            f"- Market move: Nifty {_ret(review.nifty_return_pct)}; stock vs Nifty "
            f"{'n/a' if excess is None else _ret(excess)}"
        )
    if review.vol_ratio is not None:
        lines.append(f"- Realized / predicted volatility: {review.vol_ratio:.2f}x")
    lines.append(
        f"- LLM value added: {_value_added(review.llm_value_added, 'quant baseline')}"
        if review.adjustment_applied
        else "- LLM value added: none; the LLM did not adjust that forecast"
    )
    if review.calibration_version:
        lines.append(
            f"- Calibration v{review.calibration_version} value added: "
            f"{_value_added(review.calibration_value_added, 'uncalibrated quant baseline')}"
        )
    if review.primary_cause:
        noise = " (within expected noise)" if review.expected_noise else ""
        lines.append(
            f"- Primary cause: **{review.primary_cause}**{noise} — {review.cause_explanation}"
        )
    else:
        lines.append("- Postmortem: not available yet")
    lines += [
        f"- Lesson ({lesson.status.value}, {lesson.evidence_count} confirmations): {lesson.text}"
        for lesson in review.lessons
    ]
    lines.append(
        "- One observation: it does not show whether the system is generally better or worse."
    )
    return lines


def _adaptation_lines(context: MemoryContext, snapshot: ForecastSnapshot) -> list[str]:
    """Plan.md §30 "System adaptation": the calibration in force and how it changed."""
    a = context.adaptation
    if a is None or "adaptation" not in context.learning_loaded:
        return [_NOT_LOADED]
    if not a.version:
        metrics = context.track_record.outcome_metrics if context.track_record else None
        so_far = f" ({metrics.n_forecasts} so far)" if metrics else ""
        return [
            "- No calibration yet: the quant baseline stays uncalibrated until at least "
            f"{a.min_samples} independent forecasts are scored{so_far}."
        ]
    lines = [
        f"- Calibration v{a.version}: volatility multiplier {a.previous_vol_multiplier:.2f} → "
        f"{a.vol_multiplier:.2f}; P50 shift {_ret(a.previous_p50_bias_shift_pct)} → "
        f"{_ret(a.p50_bias_shift_pct)} (estimated on {a.n_samples} scored forecasts)"
    ]
    if a.changed_since_last_forecast is True:
        lines.append("- New since the previous forecast of this ticker")
    elif a.changed_since_last_forecast is False:
        lines.append("- Unchanged since the previous forecast of this ticker")
    lines += [f"- Reason: {r}" for r in a.reason]
    if snapshot.calibration is not None:
        shadow, quant = snapshot.shadow_baseline, snapshot.quant_baseline
        lines += [
            f"- Applied to this forecast (v{snapshot.calibration.version}); the uncalibrated "
            "baseline is kept as the shadow forecast",
            f"- Effect on this forecast's quant P10–P90 range: before calibration "
            f"{_price(shadow['p10_price'])}–{_price(shadow['p90_price'])}, after "
            f"{_price(quant['p10_price'])}–{_price(quant['p90_price'])}",
        ]
    elif not a.applied:
        lines.append("- Not applied: learning is disabled (LEARNING_ENABLED=false)")
    return lines


def _track_record_lines(context: MemoryContext, regime: str) -> list[str]:
    """Plan.md §57 "Track record" plus the ticker's scorecards and regime performance."""
    if "track_record" not in context.learning_loaded:
        return [_NOT_LOADED]
    track = context.track_record
    metrics = track.outcome_metrics if track else None
    if metrics is None:
        return ["- No scored forecasts yet."]
    lines = []
    for label, w in metrics.distinct_windows():
        d = w.direction
        parts = [f"{w.n} forecasts", f"direction {d.hits}/{d.n}"]
        if d.rate is not None:
            parts[-1] += f" ({_prob(d.rate)})"
        if w.coverage_80pct is not None:
            parts.append(f"P10–P90 coverage {_prob(w.coverage_80pct)}")
        if w.brier is not None:
            parts.append(f"Brier {w.brier:.4f}")
        if w.mean_abs_error_pct is not None:
            parts.append(f"mean absolute error {w.mean_abs_error_pct:.2f}%")
        if w.mean_signed_error_pct is not None:
            parts.append(f"mean signed error {_ret(w.mean_signed_error_pct)}")
        parts.append(
            f"LLM value added {w.llm_value_added:+.4f} over {w.n_adjusted} adjusted forecasts"
            if w.llm_value_added is not None
            else "no forecast adjusted by the LLM"
        )
        lines += [f"- **{label}**: " + "; ".join(parts), f"  - {w.finding}"]
    lines.append(
        f"- Fewer than {metrics.min_samples} scored forecasts are not enough to call one "
        "forecast variant better than another."
    )
    cards = context.scorecards
    if cards is None or not cards.n_forecasts:
        return lines
    if cards.analysts:
        rates = "; ".join(
            f"{name} {h.hits}/{h.n}" + ("" if h.rate is None else f" ({_prob(h.rate)})")
            for name, h in cards.analysts.items()
        )
        lines.append(
            f"- Analyst directional hit rates ({cards.n_forecasts} independent scored forecasts; "
            f"weighting needs at least {cards.min_samples}): {rates}"
        )
    if cards.regimes:
        lines += [
            "",
            "| Regime | Forecasts | Direction | P10–P90 coverage | Brier | Mean signed error |",
            "|---|---|---|---|---|---|",
        ]
        for g in cards.regimes:
            current = " (current)" if g.group == regime else ""
            rate = "" if g.direction.rate is None else f" ({_prob(g.direction.rate)})"
            lines.append(
                f"| {g.group}{current} | {g.n} | {g.direction.hits}/{g.direction.n}{rate} "
                f"| {_prob(g.coverage_80pct)} | {g.brier:.4f} | {_ret(g.mean_signed_error_pct)} |"
            )
    return lines


def _benchmark_lines(context: MemoryContext) -> list[str]:
    """Plan.md §31/§53: naive vs quant vs calibrated quant vs final over the same forecasts."""
    if "track_record" not in context.learning_loaded:
        return [_NOT_LOADED]
    metrics = context.track_record.outcome_metrics if context.track_record else None
    windows = metrics.distinct_windows() if metrics else []
    if metrics is None or not windows:
        return ["- No scored forecasts yet."]
    label, w = windows[-1]
    if not w.variants:
        return [_NOT_LOADED]
    lines = [
        f"- **{label}**: every variant scored on the same {w.n} forecasts",
        "",
        "| Variant | Direction | P10–P90 coverage | Brier | Mean absolute error |",
        "|---|---|---|---|---|",
    ]
    for v in w.variants:
        d = v.direction
        rate = "" if d.rate is None else f" ({_prob(d.rate)})"
        coverage = "n/a" if v.coverage_80pct is None else _prob(v.coverage_80pct)
        brier = "n/a" if v.brier is None else f"{v.brier:.4f}"
        mae = "n/a" if v.mean_abs_error_pct is None else f"{v.mean_abs_error_pct:.2f}%"
        lines.append(f"| {v.label} | {d.hits}/{d.n}{rate} | {coverage} | {brier} | {mae} |")
    lines += [
        "",
        "- The naive benchmark predicts no change: it has no probabilities or range.",
        "- Lower Brier and mean absolute error are better; coverage near the band's nominal "
        "level is better than higher or lower.",
    ]
    if w.n < metrics.min_samples:
        lines.append(
            f"- With fewer than {metrics.min_samples} scored forecasts these differences "
            "are not evidence that one variant is better."
        )
    return lines


def _calibration_lines(snapshot: ForecastSnapshot) -> list[str]:
    cal = snapshot.calibration
    if cal is None:
        return ["- Calibration: none applied (the uncalibrated quant model)"]
    shadow = snapshot.shadow_baseline
    return [
        f"- Calibration v{cal.version}: volatility multiplier {cal.vol_multiplier:.2f}, "
        f"P50 shift {_ret(cal.p50_bias_shift_pct)}",
        f"- Before calibration (shadow forecast): P10 {_price(shadow['p10_price'])}, "
        f"P50 {_price(shadow['p50_price'])}, P90 {_price(shadow['p90_price'])}; "
        f"weekly volatility {shadow['weekly_vol_pct']:.2f}%",
    ]


def _render(snapshot: ForecastSnapshot) -> str:
    data = snapshot.model_dump(mode="json")
    final = snapshot.final_forecast
    quant = snapshot.quant_baseline
    gate = next(
        (d for d in snapshot.decisions if d.decision_type.value == "forecast_adjustment_gate"), None
    )
    memory = _learning_memory(snapshot)

    lines = [
        f"# Forecast report: {snapshot.ticker} ({snapshot.company_name})",
        "",
        f"- Forecast ID: `{snapshot.forecast_id}` (version {snapshot.version})",
        f"- Symbol: {snapshot.resolved_symbol}",
        f"- Made at: {data['made_at']}",
        f"- As of: {data['as_of_date']} · Target date: {data['target_date']} "
        f"({snapshot.horizon_trading_days} trading days)",
        f"- Last close: {_price(snapshot.last_close)}",
        "",
    ]
    if memory is not None:
        lines += [
            "## Last forecast vs actual",
            "",
            *_last_review_lines(memory),
            "",
            "## System adaptation",
            "",
            *_adaptation_lines(memory, snapshot),
            "",
        ]
    lines += [
        "## Prior context",
        "",
        *_review_run_lines(snapshot.data_inputs.get("review")),
        *_prior_context_lines(snapshot.data_inputs.get("memory")),
        "",
        "## Current analysis",
        "",
        f"- Market regime: **{snapshot.market_regime.value}**",
        f"- Risk category: **{snapshot.risk_category.value}**",
        "",
    ]
    for name, report in snapshot.analyst_reports.items():
        if report is None:
            lines.append(f"- **{name}**: report not available")
            continue
        lines.append(
            f"- **{name}**: {report.get('stance', 'unknown')} "
            f"(confidence {float(report.get('confidence', 0.0)):.2f})"
        )
        lines.extend(f"  - {point}" for point in report.get("key_points", []))

    lines += [
        "",
        "## Quant baseline",
        "",
        f"- Method: {quant.get('method', 'unknown')}",
        f"- Probabilities: up {_prob(quant['prob_up'])}, flat {_prob(quant['prob_flat'])}, "
        f"down {_prob(quant['prob_down'])}",
        f"- Expected return: {_ret(quant['expected_return_pct'])}",
        f"- Price range: P10 {_price(quant['p10_price'])}, P50 {_price(quant['p50_price'])}, "
        f"P90 {_price(quant['p90_price'])}",
        f"- Weekly volatility: {quant['weekly_vol_pct']:.2f}%",
        *_calibration_lines(snapshot),
        "",
        "## Decision-engine assessment",
        "",
    ]
    lines += _bullets(
        (
            f"**{d.decision_type.value}**: `{d.decision}` (confidence {d.confidence:.2f}; "
            f"{d.decision_engine}, {d.decision_model}@{d.decision_model_version}) — {d.rationale}"
            for d in snapshot.decisions
        ),
        "No decision-engine results were recorded.",
    )

    lines += [
        "",
        "## Final forecast",
        "",
        *_distribution_rows(
            [
                ("Probability up", _prob(quant["prob_up"]), _prob(final.prob_up)),
                ("Probability flat", _prob(quant["prob_flat"]), _prob(final.prob_flat)),
                ("Probability down", _prob(quant["prob_down"]), _prob(final.prob_down)),
                (
                    "Expected return",
                    _ret(quant["expected_return_pct"]),
                    _ret(final.expected_return_pct),
                ),
                ("P10 price", _price(quant["p10_price"]), _price(final.p10_price)),
                ("P50 price", _price(quant["p50_price"]), _price(final.p50_price)),
                ("P90 price", _price(quant["p90_price"]), _price(final.p90_price)),
            ]
        ),
        "",
        f"- Adjustment applied: {_yes_no(final.adjustment_applied)}",
        f"- Fell back to quant baseline: {_yes_no(final.fallback_to_quant)}",
        f"- Critic passed: {_yes_no(final.critic_passed)} (revision count {final.revision_count})",
        "",
        "## Forecast adjustments",
        "",
    ]
    if final.adjustments:
        for adj in final.adjustments:
            refs = "; ".join(adj.evidence_refs) or "none cited"
            lines.append(
                f"- {adj.adjustment_type.value}: "
                f"{_adjustment_value(adj.adjustment_type, adj.previous_value)} → "
                f"{_adjustment_value(adj.adjustment_type, adj.new_value)} — {adj.reason} "
                f"(evidence: {refs})"
            )
    else:
        lines.append("- No adjustment was applied to the quant baseline.")
    if gate is not None:
        lines.append(f"- Adjustment gate: `{gate.decision}` — {gate.rationale}")
    if final.predictor_reasoning:
        lines.append(f"- Predictor reasoning: {final.predictor_reasoning}")

    lines += ["", "## Key drivers", ""]
    lines += _bullets(final.evidence, "No supporting evidence was recorded.")

    lines += ["", "## Risks", ""]
    lines += _bullets(final.risks, "No risks were recorded.")

    lines += [
        "",
        "## Invalidation triggers",
        "",
        f"- A close on {data['target_date']} below {_price(final.p10_price)} or above "
        f"{_price(final.p90_price)} would fall outside the forecast's P10–P90 range.",
        "- Any risk listed above materialising before the target date.",
        "",
    ]
    if memory is not None:
        lines += [
            "## Track record",
            "",
            *_track_record_lines(memory, snapshot.market_regime.value),
            "",
            "## Benchmark comparison",
            "",
            *_benchmark_lines(memory),
            "",
        ]
    lines += [
        "## Data quality",
        "",
    ]
    quality = snapshot.data_quality
    lines += _bullets(
        (
            f"Guardrail violation: {v.get('message')}"
            for v in quality.get("guardrail_violations", [])
        ),
        "No guardrail violations.",
    )
    lines += [
        f"- Guardrail warning: {w.get('message')}" for w in quality.get("guardrail_warnings", [])
    ]
    lines += [f"- Warning: {w}" for w in quality.get("warnings", [])]
    lines += [
        f"- Input not available ({name}): {inputs['unavailable']}"
        for name, inputs in snapshot.data_inputs.items()
        if isinstance(inputs, dict) and inputs.get("unavailable")
    ]
    if has_advice_wording(snapshot):
        lines.append(f"- Warning: {ADVICE_WORDING_NOTE}")
    lines += [
        f"- Data gap ({g.get('analyst')}, {g.get('severity')}): {g.get('description')}"
        for g in quality.get("data_gaps", [])
    ]
    if snapshot.critic_verdict is not None:
        lines += [f"- Critic {f.severity}: {f.message}" for f in snapshot.critic_verdict.findings]

    lines += [
        "",
        "## Model and version information",
        "",
        f"- Data snapshot ID: `{snapshot.data_snapshot_id}`",
        f"- Calibration version: {snapshot.calibration_version}",
        *(f"- Model `{k}`: {v}" for k, v in sorted(snapshot.model_versions.items())),
        *(f"- Prompt `{k}`: {v}" for k, v in sorted(snapshot.prompt_versions.items())),
    ]
    if snapshot.supersedes_forecast_id:
        lines.append(
            f"- Supersedes `{snapshot.supersedes_forecast_id}`: {snapshot.correction_reason}"
        )

    lines += ["", "## Disclaimer", "", DISCLAIMER, ""]
    return "\n".join(lines)


def _leaves(value: Any) -> Iterable[Any]:
    if isinstance(value, dict):
        for v in value.values():
            yield from _leaves(v)
    elif isinstance(value, list):
        for v in value:
            yield from _leaves(v)
    else:
        yield value


def find_unsupported_numbers(report: str, snapshot: ForecastSnapshot) -> list[str]:
    """Return numbers in ``report`` that are not a formatting of a snapshot value.

    Snapshot strings (evidence, rationales, IDs, dates, model names) are removed
    first, since any digits inside them are quoted rather than introduced. Every
    remaining number must match one of the writer's formats applied to a
    snapshot number: an integer as-is, a value at 2 or 4 decimals (a loss), or a
    value x100 at 1 decimal (a probability shown as a percentage). This proves each number
    comes from the snapshot, not that it is shown next to the right label.
    """
    numbers: list[float] = []
    strings: list[str] = []
    for leaf in _leaves(snapshot.model_dump(mode="json")):
        if isinstance(leaf, bool) or leaf is None:
            continue
        if isinstance(leaf, (int, float)):
            numbers.append(float(leaf))
        elif isinstance(leaf, str):
            try:
                numbers.append(float(leaf))
            except ValueError:
                if len(leaf) >= _MIN_STRIP_LEN and any(c.isdigit() for c in leaf):
                    strings.append(leaf)

    remainder = report
    for s in sorted(set(strings), key=len, reverse=True):
        remainder = remainder.replace(s, " ")

    allowed = {f"{abs(v):.2f}" for v in numbers} | {f"{abs(v) * 100:.1f}" for v in numbers}
    allowed |= {f"{abs(v):.4f}" for v in numbers}
    allowed |= {str(int(abs(v))) for v in numbers if v.is_integer()}
    return [tok for tok in _NUMBER_RE.findall(remainder) if tok not in allowed]


def render_forecast_report(snapshot: ForecastSnapshot) -> str:
    """Render the markdown report for ``snapshot``.

    Raises:
        ReportIntegrityError: the report would contain a number not in the snapshot.
    """
    report = _render(snapshot)
    unsupported = find_unsupported_numbers(report, snapshot)
    if unsupported:
        raise ReportIntegrityError(f"Report contains unsupported numbers: {unsupported}")
    return report
